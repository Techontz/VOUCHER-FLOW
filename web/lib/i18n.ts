/**
 * Translates a dashboard key, filling `{name}` placeholders from `params`.
 * Unknown keys fall back to the English text the API sent.
 */
export function translateKey(
  key: string | null | undefined,
  locale: Locale,
  fallback: string,
  params?: Record<string, string | number> | null,
): string {
  const entry = key ? DASH[key] : undefined;
  if (!entry) return fallback;
  const text = (locale === "sw" ? entry[1] : entry[0]) || entry[0];
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    params && params[name] !== undefined ? String(params[name]) : match);
}
